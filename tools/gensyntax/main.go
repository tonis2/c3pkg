// Command gensyntax writes web/static/css/syntax.css, the stylesheet for the class names that
// internal/pkg emits when highlighting code. Run it with `go generate ./tools/gensyntax`.
package main

import (
	"bytes"
	"fmt"
	"log"
	"os"
	"strings"

	chromahtml "github.com/alecthomas/chroma/v2/formatters/html"
	"github.com/alecthomas/chroma/v2/styles"
)

//go:generate go run . ../../web/static/css/syntax.css

func skip(line string) bool {
	for _, sel := range []string{".bg ", ".chroma {", ".lnlinks", ".lntd", ".lntable", ".lnt ", ".ln ", ".hl ", ".line "} {
		if strings.Contains(line, sel) {
			return true
		}
	}
	return false
}

func main() {
	if len(os.Args) != 2 {
		log.Fatal("usage: gensyntax <output.css>")
	}
	var buf bytes.Buffer
	if err := chromahtml.New(chromahtml.WithClasses(true)).WriteCSS(&buf, styles.Get("github-dark")); err != nil {
		log.Fatal(err)
	}
	out := "/* Generated by tools/gensyntax from the chroma github-dark style. Do not edit. */\n"
	for _, line := range strings.Split(buf.String(), "\n") {
		// The block background comes from app.css (pre), and line numbers, line highlights and
		// per-line flex boxes are not used, so only keep token colours and weights.
		if skip(line) {
			continue
		}
		out += line + "\n"
	}
	if err := os.WriteFile(os.Args[1], []byte(out), 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Println("wrote", os.Args[1])
}
